import axe from 'axe-core';
import { TestBed } from '@angular/core/testing';
import { ReminderEditor } from './reminder-editor';
import { persianParts } from './persian-calendar';

describe('Reminder editor', () => {
  beforeEach(() => TestBed.configureTestingModule({ imports: [ReminderEditor] }));
  it('supports keyboard month and year navigation and emits the selected local time', async () => {
    const fixture = TestBed.createComponent(ReminderEditor);
    const initial = new Date(2030, 2, 21, 14, 30).getTime();
    fixture.componentRef.setInput('initial', initial);
    const saved = vi.fn(); fixture.componentInstance.save.subscribe(saved);
    await fixture.whenStable();
    const element: HTMLElement = fixture.nativeElement;
    expect(element.querySelector<HTMLSelectElement>('[aria-label="Hour"]')!.value).toBe('14');
    expect(element.querySelector<HTMLSelectElement>('[aria-label="Minute"]')!.value).toBe('30');
    const selected = element.querySelector<HTMLButtonElement>('[data-day][tabindex="0"]')!;
    selected.focus();
    selected.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true, cancelable: true }));
    await fixture.whenStable();
    expect(document.activeElement).toBe(element.querySelector('[data-day][tabindex="0"]'));
    expect(persianParts(fixture.componentInstance.selected()).day).toBe(2);
    const year = persianParts(fixture.componentInstance.selected()).year;
    element.querySelector<HTMLButtonElement>('[aria-label="Next year"]')!.click(); await fixture.whenStable();
    expect(persianParts(fixture.componentInstance.selected()).year).toBe(year + 1);
    fixture.componentInstance.submit();
    expect(saved).toHaveBeenCalledWith(new Date(2031, 2, 22, 14, 30).getTime());
    expect((await axe.run(element, { rules: { 'color-contrast': { enabled: false } } })).violations).toEqual([]);
  });
  it('selects a 24-hour time without typing a separator and uses English option labels', async () => {
    const fixture = TestBed.createComponent(ReminderEditor);
    fixture.componentRef.setInput('initial', new Date(2030, 2, 21, 14, 30).getTime());
    const saved = vi.fn(); fixture.componentInstance.save.subscribe(saved);
    await fixture.whenStable();
    const element: HTMLElement = fixture.nativeElement;
    const hour = element.querySelector<HTMLSelectElement>('[aria-label="Hour"]')!;
    const minute = element.querySelector<HTMLSelectElement>('[aria-label="Minute"]')!;
    expect(hour.options).toHaveLength(24);
    expect(minute.options).toHaveLength(60);
    hour.value = '23'; hour.dispatchEvent(new Event('change'));
    minute.value = '59'; minute.dispatchEvent(new Event('change'));
    await fixture.whenStable();
    expect(hour.selectedOptions[0].textContent).toBe('23');
    expect(minute.selectedOptions[0].textContent).toBe('59');
    expect(element.querySelector('.time-separator')!.textContent).toBe(':');
    fixture.componentInstance.submit();
    expect(saved).toHaveBeenCalledWith(new Date(2030, 2, 21, 23, 59).getTime());
    hour.value = '0'; hour.dispatchEvent(new Event('change'));
    minute.value = '0'; minute.dispatchEvent(new Event('change'));
    await fixture.whenStable();
    expect(fixture.componentInstance.timeText()).toBe('00:00');
  });
  it('switches calendars without changing the selected instant and navigates Gregorian months', async () => {
    const fixture = TestBed.createComponent(ReminderEditor);
    const initial = new Date(2030, 0, 31, 14, 30).getTime();
    fixture.componentRef.setInput('initial', initial);
    const saved = vi.fn(); fixture.componentInstance.save.subscribe(saved);
    await fixture.whenStable();
    const selected = fixture.componentInstance.selected().getTime();
    fixture.componentRef.setInput('calendar', 'gregory'); await fixture.whenStable();
    expect(fixture.componentInstance.selected().getTime()).toBe(selected);
    const element: HTMLElement = fixture.nativeElement;
    expect(element.querySelector('section')?.getAttribute('dir')).toBe('ltr');
    expect(element.querySelector('.month-title')?.textContent).toBe('January 2030');
    expect(fixture.componentInstance.weekdays()[0]).toBe('Sun');
    expect(fixture.componentInstance.blanks()).toHaveLength(new Date(2030, 0, 1).getDay());
    fixture.componentInstance.submit(); expect(saved).toHaveBeenLastCalledWith(initial);
    element.querySelector<HTMLButtonElement>('[aria-label="Next month"]')!.click(); await fixture.whenStable();
    expect(fixture.componentInstance.selected().getDate()).toBe(28);
    fixture.componentInstance.submit(); expect(saved).toHaveBeenLastCalledWith(new Date(2030, 1, 28, 14, 30).getTime());
    expect((await axe.run(element, { rules: { 'color-contrast': { enabled: false } } })).violations).toEqual([]);
  });
  it('retains the date and source after rejected input and disables changes while saving', async () => {
    const fixture = TestBed.createComponent(ReminderEditor); await fixture.whenStable();
    const component = fixture.componentInstance;
    component.selected.set(new Date(2000, 0, 1, 12)); component.submit(); await fixture.whenStable();
    expect(component.error()).not.toBe('');
    expect(component.selected().getFullYear()).toBe(2000);
    fixture.componentRef.setInput('busy', true); await fixture.whenStable();
    const element: HTMLElement = fixture.nativeElement;
    expect([...element.querySelectorAll<HTMLButtonElement | HTMLSelectElement>('button, select')].every(control => control.disabled)).toBe(true);
  });
});
